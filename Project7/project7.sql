// TASK 12: CONFORMED DIMENSIONS & STAR SCHEMA
// TASK 13: ADMISSION ANALYTICS - Hospital-wise Admissions

SELECT
    H.HOSPITAL_NAME,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS
FROM FACT_ADMISSION F
JOIN DIM_HOSPITAL H ON F.HOSPITAL_KEY = H.HOSPITAL_KEY
GROUP BY H.HOSPITAL_NAME
ORDER BY TOTAL_ADMISSIONS DESC;

// TASK 13.1: Admissions by Department

SELECT
    DP.DEPARTMENT_NAME,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS,
    ROUND(AVG(F.LENGTH_OF_STAY), 1) AS AVG_STAY_DAYS
FROM FACT_ADMISSION F
JOIN DIM_DEPARTMENT DP ON F.DEPARTMENT_KEY = DP.DEPARTMENT_KEY
GROUP BY DP.DEPARTMENT_NAME
ORDER BY TOTAL_ADMISSIONS DESC;

// TASK 13.2: Admissions by Doctor

SELECT
    D.DOCTOR_NAME,
    D.SPECIALIZATION,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS,
    SUM(F.LENGTH_OF_STAY) AS TOTAL_STAY_DAYS
FROM FACT_ADMISSION F
JOIN DIM_DOCTOR D ON F.DOCTOR_KEY = D.DOCTOR_KEY
GROUP BY D.DOCTOR_NAME, D.SPECIALIZATION
ORDER BY TOTAL_ADMISSIONS DESC;

// TASK 13.3: Monthly Admissions

SELECT
    DT.MONTH_NAME,
    DT.YEAR,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS
FROM FACT_ADMISSION F
JOIN DIM_DATE DT ON F.DATE_KEY = DT.DATE_KEY
GROUP BY DT.MONTH_NAME, DT.YEAR, DT.MONTH
ORDER BY DT.MONTH;

// TASK 14: HOSPITAL REVENUE ANALYTICS

SELECT
    H.HOSPITAL_NAME,
    SUM(F.NET_AMOUNT) AS TOTAL_REVENUE
FROM FACT_BILLING F
JOIN DIM_HOSPITAL H ON F.HOSPITAL_KEY = H.HOSPITAL_KEY
GROUP BY H.HOSPITAL_NAME
ORDER BY TOTAL_REVENUE DESC;

// TASK 15: MONTHLY REVENUE

SELECT
    TO_CHAR(DT.FULL_DATE, 'YYYY-MM') AS MONTH,
    SUM(F.NET_AMOUNT) AS TOTAL_REVENUE
FROM FACT_BILLING F
JOIN DIM_DATE DT ON F.DATE_KEY = DT.DATE_KEY
GROUP BY TO_CHAR(DT.FULL_DATE, 'YYYY-MM')
ORDER BY MONTH;

// TASK 16: DOCTOR-WISE REVENUE

SELECT
    D.DOCTOR_NAME,
    SUM(F.NET_AMOUNT) AS TOTAL_REVENUE
FROM FACT_BILLING F
JOIN DIM_DOCTOR D ON F.DOCTOR_KEY = D.DOCTOR_KEY
GROUP BY D.DOCTOR_NAME
ORDER BY TOTAL_REVENUE DESC;

// TASK 16.1: Revenue by Treatment

SELECT
    T.TREATMENT_NAME,
    T.TREATMENT_CATEGORY,
    SUM(F.QUANTITY) AS TOTAL_QTY,
    SUM(F.TREATMENT_AMOUNT) AS GROSS_REVENUE,
    SUM(F.DISCOUNT) AS TOTAL_DISCOUNT,
    SUM(F.NET_AMOUNT) AS NET_REVENUE
FROM FACT_BILLING F
JOIN DIM_TREATMENT T ON F.TREATMENT_KEY = T.TREATMENT_KEY
GROUP BY T.TREATMENT_NAME, T.TREATMENT_CATEGORY
ORDER BY NET_REVENUE DESC;

// TASK 16.2: Revenue by Department

SELECT
    DP.DEPARTMENT_NAME,
    SUM(F.NET_AMOUNT) AS TOTAL_REVENUE,
    COUNT(*) AS BILLING_COUNT
FROM FACT_BILLING F
JOIN DIM_DEPARTMENT DP ON F.DEPARTMENT_KEY = DP.DEPARTMENT_KEY
GROUP BY DP.DEPARTMENT_NAME
ORDER BY TOTAL_REVENUE DESC;

// TASK 17: DRILL-ACROSS ANALYSIS
// Compare Total Admissions and Total Revenue by Hospital
// (Using Conformed Dimension: DIM_HOSPITAL)

SELECT
    H.HOSPITAL_NAME,
    A.TOTAL_ADMISSIONS,
    B.TOTAL_REVENUE
FROM DIM_HOSPITAL H
LEFT JOIN (
    SELECT HOSPITAL_KEY, SUM(ADMISSION_COUNT) AS TOTAL_ADMISSIONS
    FROM FACT_ADMISSION
    GROUP BY HOSPITAL_KEY
) A ON H.HOSPITAL_KEY = A.HOSPITAL_KEY
LEFT JOIN (
    SELECT HOSPITAL_KEY, SUM(NET_AMOUNT) AS TOTAL_REVENUE
    FROM FACT_BILLING
    GROUP BY HOSPITAL_KEY
) B ON H.HOSPITAL_KEY = B.HOSPITAL_KEY
ORDER BY A.TOTAL_ADMISSIONS DESC;

// TASK 18: BUS MATRIX
// ADDITIONAL ANALYTICS

// Patient-wise Total Spend
SELECT
    P.PATIENT_NAME,
    P.CITY,
    SUM(F.NET_AMOUNT) AS TOTAL_SPEND,
    COUNT(*) AS TREATMENTS_RECEIVED
FROM FACT_BILLING F
JOIN DIM_PATIENT P ON F.PATIENT_KEY = P.PATIENT_KEY
GROUP BY P.PATIENT_NAME, P.CITY
ORDER BY TOTAL_SPEND DESC;

// Admission Duration Analysis
SELECT
    P.PATIENT_NAME,
    H.HOSPITAL_NAME,
    D.DOCTOR_NAME,
    DT.FULL_DATE AS ADMISSION_DATE,
    F.LENGTH_OF_STAY
FROM FACT_ADMISSION F
JOIN DIM_PATIENT P ON F.PATIENT_KEY = P.PATIENT_KEY
JOIN DIM_HOSPITAL H ON F.HOSPITAL_KEY = H.HOSPITAL_KEY
JOIN DIM_DOCTOR D ON F.DOCTOR_KEY = D.DOCTOR_KEY
JOIN DIM_DATE DT ON F.DATE_KEY = DT.DATE_KEY
ORDER BY F.LENGTH_OF_STAY DESC;

// Revenue per Admission (Drill-Across by Patient)
SELECT
    P.PATIENT_NAME,
    SUM(A.ADMISSION_COUNT) AS TOTAL_ADMISSIONS,
    SUM(A.LENGTH_OF_STAY) AS TOTAL_STAY_DAYS,
    B.TOTAL_BILLED
FROM FACT_ADMISSION A
JOIN DIM_PATIENT P ON A.PATIENT_KEY = P.PATIENT_KEY
LEFT JOIN (
    SELECT PATIENT_KEY, SUM(NET_AMOUNT) AS TOTAL_BILLED
    FROM FACT_BILLING
    GROUP BY PATIENT_KEY
) B ON P.PATIENT_KEY = B.PATIENT_KEY
GROUP BY P.PATIENT_NAME, B.TOTAL_BILLED
ORDER BY B.TOTAL_BILLED DESC;

