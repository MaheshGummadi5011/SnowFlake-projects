// TASK 9: DEFINE FACT_BILLING GRAIN
// TASK 10: IDENTIFY MEASURES
// TASK 11: LOAD FACT_ADMISSION

INSERT INTO FACT_ADMISSION (PATIENT_KEY, DOCTOR_KEY, HOSPITAL_KEY, DEPARTMENT_KEY, DATE_KEY, ADMISSION_COUNT, LENGTH_OF_STAY)
SELECT
    P.PATIENT_KEY,
    D.DOCTOR_KEY,
    H.HOSPITAL_KEY,
    DP.DEPARTMENT_KEY,
    DT.DATE_KEY,
    1 AS ADMISSION_COUNT,
    DATEDIFF(DAY, A.ADMISSION_DATE, A.DISCHARGE_DATE) AS LENGTH_OF_STAY
FROM STAGING.STG_ADMISSIONS A
JOIN DIM_PATIENT P ON A.PATIENT_ID = P.PATIENT_ID
JOIN DIM_DOCTOR D ON A.DOCTOR_ID = D.DOCTOR_ID
JOIN DIM_HOSPITAL H ON A.HOSPITAL_ID = H.HOSPITAL_ID
JOIN DIM_DEPARTMENT DP ON A.DEPARTMENT_ID = DP.DEPARTMENT_ID
JOIN DIM_DATE DT ON DT.FULL_DATE = A.ADMISSION_DATE;

// Verify
SELECT COUNT(*) AS FACT_ADMISSION_ROWS FROM FACT_ADMISSION;

// TASK 11.1: LOAD FACT_BILLING

INSERT INTO FACT_BILLING (PATIENT_KEY, DOCTOR_KEY, HOSPITAL_KEY, DEPARTMENT_KEY, TREATMENT_KEY, DATE_KEY, QUANTITY, TREATMENT_AMOUNT, DISCOUNT, NET_AMOUNT)
