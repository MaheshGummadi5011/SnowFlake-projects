// TASK 4: CREATE & LOAD DIM_DATE (2026-01-01 to 2026-03-31)

CREATE OR REPLACE TABLE DIM_DATE (
    DATE_KEY NUMBER PRIMARY KEY,
    FULL_DATE DATE,
    DAY NUMBER,
    DAY_NAME VARCHAR(20),
    WEEK_NO NUMBER,
    MONTH NUMBER,
    MONTH_NAME VARCHAR(20),
    QUARTER VARCHAR(5),
    YEAR NUMBER
);

INSERT INTO DIM_DATE
SELECT
    TO_NUMBER(TO_CHAR(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE), 'YYYYMMDD')) AS DATE_KEY,
    DATEADD(DAY, SEQ4(), '2026-01-01'::DATE) AS FULL_DATE,
    DAY(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE)) AS DAY,
    DAYNAME(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE)) AS DAY_NAME,
    WEEKOFYEAR(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE)) AS WEEK_NO,
    MONTH(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE)) AS MONTH,
    MONTHNAME(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE)) AS MONTH_NAME,
    CONCAT('Q', QUARTER(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE))) AS QUARTER,
    YEAR(DATEADD(DAY, SEQ4(), '2026-01-01'::DATE)) AS YEAR
FROM TABLE(GENERATOR(ROWCOUNT => 90))
WHERE DATEADD(DAY, SEQ4(), '2026-01-01'::DATE) <= '2026-03-31'::DATE;

