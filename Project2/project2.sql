// PHASE 4 - WINDOW FUNCTIONS

// 1. Rank Customers Based on Total Spending
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING,
    RANK() OVER(ORDER BY SUM(S.TOTAL_AMOUNT) DESC) AS CUSTOMER_RANK
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY CUSTOMER_RANK;

// 2. Rank Branches Based on Total Sales
SELECT
    B.BRANCH_ID,
    B.BRANCH_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    RANK() OVER(ORDER BY SUM(S.TOTAL_AMOUNT) DESC) AS BRANCH_RANK
FROM BRANCHES B
JOIN SALES S
    ON B.BRANCH_ID = S.BRANCH_ID
GROUP BY
    B.BRANCH_ID,
    B.BRANCH_NAME
ORDER BY BRANCH_RANK;

// 3. Top-Selling Product in Each Category
SELECT
    CATEGORY,
    PRODUCT_NAME,
    TOTAL_REVENUE
FROM (
    SELECT
        P.CATEGORY,
        P.PRODUCT_NAME,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE,
        ROW_NUMBER() OVER(
            PARTITION BY P.CATEGORY
            ORDER BY SUM(S.TOTAL_AMOUNT) DESC
        ) AS RN
    FROM PRODUCTS P
    JOIN SALES S
        ON P.PRODUCT_ID = S.PRODUCT_ID
    GROUP BY
        P.CATEGORY,
        P.PRODUCT_NAME
)
WHERE RN = 1;

// 4. Cumulative Sales Report
SELECT
    SALE_ID,
    SALE_DATE,
    TOTAL_AMOUNT,
    SUM(TOTAL_AMOUNT) OVER(
        ORDER BY SALE_DATE
    ) AS CUMULATIVE_SALES
FROM SALES
ORDER BY SALE_DATE;

// 5. Average Sale Amount
SELECT
    SALE_ID,
    SALE_DATE,
    TOTAL_AMOUNT,
    AVG(TOTAL_AMOUNT) OVER() AS AVERAGE_SALE_AMOUNT
FROM SALES
ORDER BY SALE_DATE;

// PHASE 5 - CTE (COMMON TABLE EXPRESSIONS)

// 1. Customer-wise Revenue Using CTE
WITH CUSTOMER_REVENUE AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
    FROM CUSTOMERS C
    JOIN SALES S
        ON C.CUSTOMER_ID = S.CUSTOMER_ID
    GROUP BY
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME
)
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    TOTAL_REVENUE
FROM CUSTOMER_REVENUE
ORDER BY TOTAL_REVENUE DESC;

// 2. Customers Spending Greater Than Average Spending
WITH CUSTOMER_REVENUE AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING
    FROM CUSTOMERS C
    JOIN SALES S
        ON C.CUSTOMER_ID = S.CUSTOMER_ID
    GROUP BY
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME
)
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    TOTAL_SPENDING
FROM CUSTOMER_REVENUE
WHERE TOTAL_SPENDING > (
    SELECT AVG(TOTAL_SPENDING)
    FROM CUSTOMER_REVENUE
)
ORDER BY TOTAL_SPENDING DESC;

// PHASE 6 - VIEWS & MATERIALIZED VIEWS

// 1. Create SALES_REPORT View
CREATE OR REPLACE VIEW SALES_REPORT AS
SELECT
    S.SALE_ID,
    S.SALE_DATE,
    C.CUSTOMER_NAME,
    P.PRODUCT_NAME,
    P.CATEGORY,
    B.BRANCH_NAME,
    S.QUANTITY,
    S.TOTAL_AMOUNT
FROM SALES S
JOIN CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
JOIN PRODUCTS P
    ON S.PRODUCT_ID = P.PRODUCT_ID
JOIN BRANCHES B
    ON S.BRANCH_ID = B.BRANCH_ID;

// 2. Query SALES_REPORT View
SELECT *
FROM SALES_REPORT
ORDER BY SALE_DATE;

// 3. Create TOP_CUSTOMERS View
CREATE OR REPLACE VIEW TOP_CUSTOMERS AS
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME;

// 4. Query TOP_CUSTOMERS View
SELECT *
FROM TOP_CUSTOMERS
ORDER BY TOTAL_SPENDING DESC;

// 5. Display Top 3 Customers
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    TOTAL_SPENDING
FROM TOP_CUSTOMERS
ORDER BY TOTAL_SPENDING DESC
