// PHASE 10: ANALYTICAL REPORTS (Snowflake Schema Queries)

// Report 1: Customer-wise Sales Report
SELECT
    C.CUSTOMER_NAME,
    CT.CITY_NAME,
    S.STATE_NAME,
    C.MEMBERSHIP,
    SUM(F.QUANTITY) AS TOTAL_QTY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_CUSTOMER C ON F.CUSTOMER_ID = C.CUSTOMER_ID
JOIN DIM_CITY CT ON C.CITY_ID = CT.CITY_ID
JOIN DIM_STATE S ON CT.STATE_ID = S.STATE_ID
GROUP BY C.CUSTOMER_NAME, CT.CITY_NAME, S.STATE_NAME, C.MEMBERSHIP
ORDER BY TOTAL_REVENUE DESC;

// Report 2: Product-wise Revenue Report
SELECT
    P.PRODUCT_NAME,
    CAT.CATEGORY_NAME,
    B.BRAND_NAME,
    P.PRICE,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRAND B ON P.BRAND_ID = B.BRAND_ID
JOIN DIM_CATEGORY CAT ON B.CATEGORY_ID = CAT.CATEGORY_ID
GROUP BY P.PRODUCT_NAME, CAT.CATEGORY_NAME, B.BRAND_NAME, P.PRICE
ORDER BY TOTAL_REVENUE DESC;

// Report 3: Brand-wise Revenue Report
SELECT
    B.BRAND_NAME,
    CAT.CATEGORY_NAME,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRAND B ON P.BRAND_ID = B.BRAND_ID
JOIN DIM_CATEGORY CAT ON B.CATEGORY_ID = CAT.CATEGORY_ID
GROUP BY B.BRAND_NAME, CAT.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;

// Report 4: Category-wise Revenue Report
SELECT
    CAT.CATEGORY_NAME,
    SUM(F.QUANTITY) AS TOTAL_QTY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    COUNT(*) AS TOTAL_TRANSACTIONS
FROM FACT_SALES F
JOIN DIM_PRODUCT P ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRAND B ON P.BRAND_ID = B.BRAND_ID
JOIN DIM_CATEGORY CAT ON B.CATEGORY_ID = CAT.CATEGORY_ID
GROUP BY CAT.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;

