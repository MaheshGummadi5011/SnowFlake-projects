// PHASE 2: ANALYZE EXISTING STAR SCHEMA
// PHASE 3: CREATE LOOKUP TABLES (Normalized Hierarchies)

USE SCHEMA ANALYTICS;

// GEOGRAPHIC HIERARCHY: Region > State > City

// DIM_REGION
CREATE OR REPLACE TABLE DIM_REGION (
    REGION_ID NUMBER PRIMARY KEY,
    REGION_NAME VARCHAR(50)
);

// DIM_STATE
CREATE OR REPLACE TABLE DIM_STATE (
    STATE_ID NUMBER PRIMARY KEY,
    STATE_NAME VARCHAR(100),
    REGION_ID NUMBER REFERENCES DIM_REGION(REGION_ID)
);

// DIM_CITY
CREATE OR REPLACE TABLE DIM_CITY (
    CITY_ID NUMBER PRIMARY KEY,
    CITY_NAME VARCHAR(100),
    STATE_ID NUMBER REFERENCES DIM_STATE(STATE_ID)
);

// PRODUCT HIERARCHY: Category > Brand

// DIM_CATEGORY
CREATE OR REPLACE TABLE DIM_CATEGORY (
    CATEGORY_ID NUMBER PRIMARY KEY,
    CATEGORY_NAME VARCHAR(100)
);

// DIM_BRAND
CREATE OR REPLACE TABLE DIM_BRAND (
    BRAND_ID NUMBER PRIMARY KEY,
    BRAND_NAME VARCHAR(100),
    CATEGORY_ID NUMBER REFERENCES DIM_CATEGORY(CATEGORY_ID)
);

// DATE HIERARCHY: Year > Quarter > Month

// DIM_YEAR
CREATE OR REPLACE TABLE DIM_YEAR (
    YEAR_ID NUMBER PRIMARY KEY,
    YEAR_VALUE NUMBER
);

// DIM_QUARTER
CREATE OR REPLACE TABLE DIM_QUARTER (
    QUARTER_ID NUMBER PRIMARY KEY,
    QUARTER_NAME VARCHAR(10),
    YEAR_ID NUMBER REFERENCES DIM_YEAR(YEAR_ID)
);

// DIM_MONTH
CREATE OR REPLACE TABLE DIM_MONTH (
    MONTH_ID NUMBER PRIMARY KEY,
    MONTH_NAME VARCHAR(20),
    QUARTER_ID NUMBER REFERENCES DIM_QUARTER(QUARTER_ID)
);

// PHASE 4: CREATE NORMALIZED DIMENSION TABLES

// DIM_CUSTOMER (Normalized - references DIM_CITY)
CREATE OR REPLACE TABLE DIM_CUSTOMER (
    CUSTOMER_ID NUMBER PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(100),
    CITY_ID NUMBER REFERENCES DIM_CITY(CITY_ID),
    MEMBERSHIP VARCHAR(50)
);

// DIM_PRODUCT (Normalized - references DIM_BRAND)
CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_ID NUMBER PRIMARY KEY,
    PRODUCT_NAME VARCHAR(100),
    BRAND_ID NUMBER REFERENCES DIM_BRAND(BRAND_ID),
    PRICE NUMBER(12,2)
);

// DIM_BRANCH (Normalized - references DIM_CITY)
CREATE OR REPLACE TABLE DIM_BRANCH (
    BRANCH_ID NUMBER PRIMARY KEY,
    BRANCH_NAME VARCHAR(150),
    CITY_ID NUMBER REFERENCES DIM_CITY(CITY_ID),
    MANAGER_NAME VARCHAR(100)
);

// DIM_DATE (Normalized - references DIM_MONTH)
CREATE OR REPLACE TABLE DIM_DATE (
    DATE_ID NUMBER PRIMARY KEY,
    DATE DATE,
    DAY NUMBER,
    DAY_NAME VARCHAR(20),
    WEEK_NO NUMBER,
    MONTH_ID NUMBER REFERENCES DIM_MONTH(MONTH_ID),
    IS_WEEKEND VARCHAR(10)
);

// PHASE 5: CREATE FACT TABLE

CREATE OR REPLACE TABLE FACT_SALES (
    SALE_ID NUMBER PRIMARY KEY,
    CUSTOMER_ID NUMBER REFERENCES DIM_CUSTOMER(CUSTOMER_ID),
    PRODUCT_ID NUMBER REFERENCES DIM_PRODUCT(PRODUCT_ID),
    BRANCH_ID NUMBER REFERENCES DIM_BRANCH(BRANCH_ID),
    DATE_ID NUMBER REFERENCES DIM_DATE(DATE_ID),
    QUANTITY NUMBER,
    TOTAL_AMOUNT NUMBER(12,2)
);

